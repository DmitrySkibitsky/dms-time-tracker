// Bundles the TypeScript sources into ES modules the QML engine can import.
//   node scripts/build.mjs          -> lib/tracker.mjs (committed, shipped with the plugin)
//   node scripts/build.mjs --test   -> also tests/qml/generated/fakes.mjs (test-only)

import { readFileSync, writeFileSync } from "node:fs";
import { build } from "esbuild";

// Built-ins missing from the QML V4 engine (verified on Qt 6.11). esbuild lowers syntax
// but does not polyfill methods, so a bundle using these would throw inside the shell.
const UNSUPPORTED = [
    [/\bglobalThis\b/, "globalThis (not defined in V4 ES modules)"],
    [/\.(flat|flatMap|at|findLast|findLastIndex|replaceAll|trimEnd|trimStart|finally)\(/, "Array/String/Promise method missing in V4"],
    [/\bObject\.(fromEntries|hasOwn)\b/, "Object method missing in V4"],
    [/\bPromise\.(allSettled|any)\b/, "Promise combinator missing in V4"],
    [/\bstructuredClone\b/, "structuredClone"],
    // V4 has no native async/await; esbuild lowers it to generators, and resuming a generator
    // segfaults V4 (QV4::GeneratorObject::resume, Qt 6.11). Use promise chains in src/.
    [/\bfunction\s*\*|\b__async\b|\byield\b/, "generators / async functions (crash the QML engine)"]
];

// qmllint/qmlls only see exports written as `export function f` / `export var x`; esbuild
// emits a trailing `export { f, x }` list instead, which makes every `Tracker.f` an unknown
// member in editors. Rewrite the list into inline export declarations.
function inlineExports(file) {
    let code = readFileSync(file, "utf8");
    const list = /\nexport \{([^}]*)\};\s*$/.exec(code);
    if (!list) return;
    code = code.slice(0, list.index + 1);
    for (const raw of list[1].split(",")) {
        const name = raw.trim();
        if (!name) continue;
        if (/\s+as\s+/.test(name)) {
            console.error(`${file}: esbuild renamed export "${name}" (name clash); rename the source symbol.`);
            process.exit(1);
        }
        const decl = new RegExp(`^((?:async )?function\\*? ${name}\\(|(?:var|let|const|class) ${name}\\b)`, "m");
        if (!decl.test(code)) {
            console.error(`${file}: no top-level declaration found for export "${name}"`);
            process.exit(1);
        }
        code = code.replace(decl, "export $1");
    }
    writeFileSync(file, code);
}

function assertQmlCompatible(file) {
    const code = readFileSync(file, "utf8");
    const problems = [];
    for (const [pattern, why] of UNSUPPORTED) {
        const match = pattern.exec(code);
        if (match) problems.push(`${file}: "${match[0]}" — ${why}`);
    }
    if (problems.length) {
        console.error(`Bundle uses APIs the QML engine lacks:\n  ${problems.join("\n  ")}`);
        process.exit(1);
    }
}

// The QML V4 engine implements ES2016 plus selected later features; lowering async/await,
// class fields and optional chaining keeps the bundle portable across Qt 6 versions.
const common = {
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2016",
    charset: "utf8",
    legalComments: "none",
    logLevel: "warning"
};

const banner = "// GENERATED by scripts/build.mjs from src/ -- do not edit. Run `npm run build`.";

await build({
    ...common,
    entryPoints: ["src/qml/index.ts"],
    outfile: "lib/tracker.mjs",
    banner: { js: banner }
});
inlineExports("lib/tracker.mjs");
assertQmlCompatible("lib/tracker.mjs");

if (process.argv.includes("--test")) {
    await build({
        ...common,
        entryPoints: ["tests/fakes/index.ts"],
        outfile: "tests/qml/generated/fakes.mjs",
        banner: { js: banner }
    });
    inlineExports("tests/qml/generated/fakes.mjs");
    assertQmlCompatible("tests/qml/generated/fakes.mjs");
}
